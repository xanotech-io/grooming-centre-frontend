import dayjs from "dayjs";
import { exportRowsToCsv, exportRowsToExcel, exportRowsToPdf } from "../../../utils/exportToCsv";

const EXTENSION_BY_FORMAT = { json: "json", pdf: "pdf", excel: "xlsx", csv: "csv" };

const humanizeKey = (key) =>
  String(key)
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/_/g, " ")
    .replace(/^./, (s) => s.toUpperCase())
    .trim();

const isRecordList = (val) =>
  Array.isArray(val) && val.length > 0 && val.every((v) => v && typeof v === "object" && !Array.isArray(v));

const formatValue = (val) => {
  if (val === null || val === undefined || val === "") return "—";
  if (typeof val === "boolean") return val ? "Yes" : "No";
  if (Array.isArray(val)) return val.length ? val.map(formatValue).join(", ") : "—";
  if (typeof val === "object") {
    const entries = Object.entries(val);
    return entries.length ? entries.map(([k, v]) => `${humanizeKey(k)}: ${formatValue(v)}`).join(" · ") : "—";
  }
  return String(val);
};

// a list of records (e.g. per-department breakdown) becomes its own table under a section heading
const recordTableRows = (title, records) => {
  const columns = [...new Set(records.flatMap((r) => Object.keys(r)))];
  return [
    [],
    [title],
    columns.map(humanizeKey),
    ...records.map((r) => columns.map((c) => formatValue(r[c]))),
  ];
};

// keys on the report record that are metadata, not report data
const META_KEYS = new Set([
  "id", "_id", "reportId", "reportName", "reportCategory", "reportFormat", "status", "generatedBy",
  "generatedDate", "recordCount", "frequency", "accessLevel", "dataSources", "remarks", "filtersApplied",
  "filters", "summary", "downloadUrl", "generationTimeMs", "isScheduled", "metrics", "createdAt", "updatedAt",
  "deletedAt", "__v",
]);

// Builds the report's own contents (details, filters, summary metrics and any record lists)
// as rows for the shared CSV/Excel/PDF exporters.
// `resolveValue(key, value)` lets the caller map raw ids (generatedBy, filter ids) to names.
export const buildMISReportRows = (report, resolveValue = (_k, v) => v) => {
  const rows = [
    ["Field", "Value"],
    ["Report ID", formatValue(report.reportId)],
    ["Report Name", formatValue(report.reportName)],
    ["Category", humanizeKey(report.reportCategory ?? "—")],
    ["Status", humanizeKey(report.status ?? "—")],
    ["Generated By", formatValue(resolveValue("generatedBy", report.generatedBy))],
    ["Generated Date", report.generatedDate ? dayjs(report.generatedDate).format("DD/MM/YYYY") : "—"],
    ["Frequency", humanizeKey(report.frequency ?? "—")],
    ["Record Count", formatValue(report.recordCount)],
    ["Access Level", formatValue(report.accessLevel)],
    ["Data Sources", formatValue(report.dataSources)],
    ["Remarks", formatValue(report.remarks)],
  ];
  const tables = [];

  const filterEntries = Object.entries(report.filtersApplied ?? report.filters ?? {})
    .filter(([, v]) => v !== null && v !== undefined && v !== "");
  if (filterEntries.length) {
    rows.push([], ["Filters Applied"]);
    // ids are resolved to names, so "departmentId" reads as "Department"
    filterEntries.forEach(([k, v]) => rows.push([humanizeKey(k).replace(/ Id$/, ""), formatValue(resolveValue(k, v))]));
  }

  const summaryEntries = Object.entries(report.summary ?? {});
  if (summaryEntries.length) {
    rows.push([], ["Report Summary"]);
    summaryEntries.forEach(([k, v]) => {
      if (isRecordList(v)) tables.push(recordTableRows(humanizeKey(k), v));
      else rows.push([humanizeKey(k), formatValue(v)]);
    });
  }

  // any record-level data the backend includes alongside the summary (e.g. data/records/rows)
  Object.entries(report)
    .filter(([k, v]) => !META_KEYS.has(k) && isRecordList(v))
    .forEach(([k, v]) => tables.push(recordTableRows(humanizeKey(k), v)));

  return [...rows, ...tables.flat()];
};

export const exportMISReport = (report, format, resolveValue) => {
  const fmt = format || report.reportFormat || "json";
  const base = (report.reportName || report.reportId || "report").replace(/[^\w-]+/g, "_");
  const filename = `${base}.${EXTENSION_BY_FORMAT[fmt] ?? fmt}`;

  if (fmt === "json") {
    const blob = new Blob([JSON.stringify(report, null, 2)], { type: "application/json" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    link.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
    return;
  }

  const rows = buildMISReportRows(report, resolveValue);
  if (fmt === "csv") exportRowsToCsv(rows, filename);
  else if (fmt === "excel") exportRowsToExcel(rows, filename);
  else if (fmt === "pdf") exportRowsToPdf(rows, filename, report.reportName || "MIS Report");
  else throw new Error(`Unsupported export format: ${fmt}`);
};
